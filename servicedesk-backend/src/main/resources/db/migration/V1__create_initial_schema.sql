
-- V1: Initial ServiceDesk Pro database schema
-- Intended for a fresh, empty production database.

-- 1. Roles
CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(255) NOT NULL,
                       CONSTRAINT uk_roles_name UNIQUE (name)
);

-- 2. Users
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(255),
                       email VARCHAR(255) NOT NULL,
                       password VARCHAR(255),
                       role_id BIGINT NOT NULL,
                       CONSTRAINT uk_users_email UNIQUE (email),
                       CONSTRAINT fk_users_role
                           FOREIGN KEY (role_id) REFERENCES roles(id)
);

-- 3. Tickets
CREATE TABLE tickets (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         title VARCHAR(255) NOT NULL,
                         description TEXT NOT NULL,
                         status VARCHAR(255) NOT NULL,
                         priority VARCHAR(255) NOT NULL,
                         category VARCHAR(255) NOT NULL,
                         created_by BIGINT NOT NULL,
                         assigned_to BIGINT,
                         created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
                         updated_at TIMESTAMP(6) WITHOUT TIME ZONE,

                         CONSTRAINT fk_tickets_created_by
                             FOREIGN KEY (created_by) REFERENCES users(id),
                         CONSTRAINT fk_tickets_assigned_to
                             FOREIGN KEY (assigned_to) REFERENCES users(id),

                         CONSTRAINT chk_tickets_status
                             CHECK (status IN (
                                               'OPEN', 'ASSIGNED', 'IN_PROGRESS',
                                               'RESOLVED', 'CLOSED', 'CANCELLED'
                                 )),
                         CONSTRAINT chk_tickets_priority
                             CHECK (priority IN (
                                                 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
                                 )),
                         CONSTRAINT chk_tickets_category
                             CHECK (category IN (
                                                 'HARDWARE', 'SOFTWARE', 'NETWORK',
                                                 'ACCOUNT', 'SECURITY', 'OTHER'
                                 ))
);

-- 4. Comments
CREATE TABLE comments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          ticket_id BIGINT NOT NULL,
                          content TEXT NOT NULL,
                          created_by BIGINT NOT NULL,
                          created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                          CONSTRAINT fk_comments_ticket
                              FOREIGN KEY (ticket_id) REFERENCES tickets(id),
                          CONSTRAINT fk_comments_created_by
                              FOREIGN KEY (created_by) REFERENCES users(id)
);

-- 5. Ticket status history
CREATE TABLE ticket_status_history (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       ticket_id BIGINT NOT NULL,
                                       from_status VARCHAR(255) NOT NULL,
                                       to_status VARCHAR(255) NOT NULL,
                                       changed_by BIGINT NOT NULL,
                                       changed_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                                       CONSTRAINT fk_status_history_ticket
                                           FOREIGN KEY (ticket_id) REFERENCES tickets(id),
                                       CONSTRAINT fk_status_history_changed_by
                                           FOREIGN KEY (changed_by) REFERENCES users(id),

                                       CONSTRAINT chk_status_history_from
                                           CHECK (from_status IN (
                                                                  'OPEN', 'ASSIGNED', 'IN_PROGRESS',
                                                                  'RESOLVED', 'CLOSED', 'CANCELLED'
                                               )),
                                       CONSTRAINT chk_status_history_to
                                           CHECK (to_status IN (
                                                                'OPEN', 'ASSIGNED', 'IN_PROGRESS',
                                                                'RESOLVED', 'CLOSED', 'CANCELLED'
                                               ))
);

-- 6. Ticket assignment history
CREATE TABLE ticket_assignment_history (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           ticket_id BIGINT NOT NULL,
                                           assigned_to BIGINT NOT NULL,
                                           assigned_by BIGINT NOT NULL,
                                           assigned_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                                           CONSTRAINT fk_assignment_history_ticket
                                               FOREIGN KEY (ticket_id) REFERENCES tickets(id),
                                           CONSTRAINT fk_assignment_history_assigned_to
                                               FOREIGN KEY (assigned_to) REFERENCES users(id),
                                           CONSTRAINT fk_assignment_history_assigned_by
                                               FOREIGN KEY (assigned_by) REFERENCES users(id)
);
